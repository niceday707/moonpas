-- ── 테이블 정의 ──────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS courses (
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  name        TEXT        NOT NULL,
  category    TEXT        NOT NULL CHECK (category IN ('일반선택', '진로선택', '융합선택')),
  area        TEXT        NOT NULL,
  streams     TEXT[]      NOT NULL DEFAULT '{}',
  description TEXT        NOT NULL,
  detail      TEXT        NOT NULL,
  recommended_for  TEXT   NOT NULL,
  related_majors   TEXT[] NOT NULL DEFAULT '{}',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS course_reviews (
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  course_id   UUID        NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  author_id   TEXT        NOT NULL,
  author_name TEXT        NOT NULL,
  author_role TEXT        NOT NULL CHECK (author_role IN ('student', 'teacher', 'parent', 'alumni')),
  content     TEXT        NOT NULL,
  rating      INTEGER     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  difficulty  TEXT        NOT NULL CHECK (difficulty IN ('쉬움', '보통', '어려움')),
  recommended BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS course_qna (
  id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  course_id    UUID        REFERENCES courses(id) ON DELETE SET NULL,
  author_id    TEXT        NOT NULL,
  author_name  TEXT        NOT NULL,
  question     TEXT        NOT NULL,
  answer       TEXT,
  answered_by  TEXT,
  answered_at  TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- updated_at 자동 갱신 트리거
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER courses_updated_at
  BEFORE UPDATE ON courses
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── Row Level Security ────────────────────────────────────────

ALTER TABLE courses        ENABLE ROW LEVEL SECURITY;
ALTER TABLE course_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE course_qna     ENABLE ROW LEVEL SECURITY;

-- 과목 정보: 모든 인증 사용자 읽기, 교사만 쓰기 (role 컬럼은 auth.users에서 관리)
CREATE POLICY "courses_select" ON courses FOR SELECT USING (TRUE);
CREATE POLICY "courses_insert" ON courses FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "courses_update" ON courses FOR UPDATE USING (auth.role() = 'authenticated');

-- 후기: 모든 인증 사용자 읽기·쓰기
CREATE POLICY "reviews_select" ON course_reviews FOR SELECT USING (TRUE);
CREATE POLICY "reviews_insert" ON course_reviews FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Q&A: 모든 인증 사용자 읽기·쓰기
CREATE POLICY "qna_select" ON course_qna FOR SELECT USING (TRUE);
CREATE POLICY "qna_insert" ON course_qna FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "qna_update" ON course_qna FOR UPDATE USING (auth.role() = 'authenticated');

